const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const HTTP_METHODS = new Set(['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']);

function deriveSuccessStatuses(document, sourceLabel = 'OpenAPI document') {
    if (!document || typeof document !== 'object' || !document.paths || typeof document.paths !== 'object') {
        throw new Error(`${sourceLabel} must contain a paths object.`);
    }

    const statuses = {};
    for (const [route, pathItem] of Object.entries(document.paths)) {
        if (!pathItem || typeof pathItem !== 'object') continue;
        for (const [method, operation] of Object.entries(pathItem)) {
            if (!HTTP_METHODS.has(method.toLowerCase()) || !operation || typeof operation !== 'object') continue;

            const location = `${method.toUpperCase()} ${route}`;
            const { operationId, responses } = operation;
            if (!operationId) throw new Error(`${sourceLabel}: ${location} has no operationId.`);
            if (Object.prototype.hasOwnProperty.call(statuses, operationId)) {
                throw new Error(`${sourceLabel}: duplicate operationId '${operationId}'.`);
            }
            if (!responses || typeof responses !== 'object') {
                throw new Error(`${sourceLabel}: operation '${operationId}' has no responses object.`);
            }

            const successCodes = Object.keys(responses)
                .filter((code) => /^2\d\d$/.test(String(code)))
                .map(Number)
                .sort((left, right) => left - right);

            if (successCodes.length === 0) {
                throw new Error(`${sourceLabel}: operation '${operationId}' has no numeric 2xx response.`);
            }
            if (successCodes.length > 1) {
                throw new Error(`${sourceLabel}: operation '${operationId}' has ambiguous 2xx responses: ${successCodes.join(', ')}.`);
            }
            statuses[operationId] = successCodes[0];
        }
    }

    return Object.fromEntries(Object.entries(statuses).sort(([left], [right]) => left.localeCompare(right)));
}

function renderMetadata(statuses, sourcePath) {
    const entries = Object.entries(statuses)
        .map(([operationId, status]) => `    ${JSON.stringify(operationId)}: ${status},`)
        .join('\n');
    return `'use strict';\n\n// Generated by scripts/generate-openapi-response-metadata.js from ${sourcePath}.\n// Do not edit this file manually.\nmodule.exports = Object.freeze({\n${entries}\n});\n`;
}

function generateMetadata(inputPath, outputPath) {
    const source = fs.readFileSync(inputPath, 'utf8');
    const document = yaml.load(source);
    const statuses = deriveSuccessStatuses(document, inputPath);
    const rendered = renderMetadata(statuses, path.relative(path.dirname(outputPath), inputPath).split(path.sep).join('/'));
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, rendered);
    return statuses;
}

if (require.main === module) {
    const root = path.join(__dirname, '..');
    const inputPath = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'openapi', 'openapi.yaml');
    const outputPath = process.argv[3]
        ? path.resolve(process.argv[3])
        : path.join(root, 'adapters', 'openapi-generator', 'generated-response-metadata.js');

    try {
        const statuses = generateMetadata(inputPath, outputPath);
        console.log(`Generated success response metadata for ${Object.keys(statuses).length} operations.`);
    } catch (error) {
        console.error(`Unable to generate OpenAPI response metadata: ${error.message}`);
        process.exitCode = 1;
    }
}

module.exports = { deriveSuccessStatuses, generateMetadata, renderMetadata };
